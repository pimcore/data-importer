// Fetches the OpenAPI doc from a running Studio instance and writes it to
// docs.jsonopenapi.json, applying a small set of known corrections first.
//
// Why corrections exist at all: docs.jsonopenapi.json is generated by whatever
// Studio instance STUDIO_API_DOCS_URL points at. That instance can lag behind
// this repo's own #[Property] annotations (e.g. right after a fix here merges
// but before the instance redeploys), and `npm run build-api-client` trusts
// this file literally. Left unpatched, refreshing the snapshot from a stale
// instance silently regenerates the wrong TypeScript type for the frontend.
// See git commit 59ee843 (dataSourceIndex integer -> string) for the incident
// this guards against.
//
// Usage:
//   STUDIO_API_DOCS_URL="https://bugfix.nightly.pimcore.app/pimcore-studio/api/docs/json?locale=en" \
//     npm run fetch-api-docs

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const OUTPUT_PATH = join(dirname(fileURLToPath(import.meta.url)), 'docs.jsonopenapi.json')

// Each correction is applied as a literal string substitution against the raw
// (minified) response body, not a parse/re-serialize round trip, so untouched
// parts of the ~1.4 MB doc keep their exact upstream formatting and the diff
// stays scoped to what actually changed.
const KNOWN_CORRECTIONS = [
  {
    name: 'BundleDataImporterCalculateTransformationResultTypeParameters.currentConfig.dataSourceIndex',
    reason: 'dataSourceIndex holds string column identifiers everywhere else in the ' +
      'bundle (ColumnHeadersResponse.id/dataIndex, frontend types.ts MappingConfigItem, ' +
      'both callers of the generated query), but the PHP annotation in ' +
      'CalculateTransformationResultTypeParameters.php types the array items as integer.',
    find: '"dataSourceIndex":{"description":"Data source column indices","type":"array","items":{"type":"integer"},"example":[0]}',
    replace: '"dataSourceIndex":{"description":"Data source column indices","type":"array","items":{"type":"string"},"example":["0"]}'
  }
]

async function main () {
  const url = process.env.STUDIO_API_DOCS_URL
  if (url === undefined || url === '') {
    console.error(
      'STUDIO_API_DOCS_URL is not set.\n' +
      'Point it at a running Studio instance\'s OpenAPI doc endpoint, e.g.:\n' +
      '  STUDIO_API_DOCS_URL="https://bugfix.nightly.pimcore.app/pimcore-studio/api/docs/json?locale=en" npm run fetch-api-docs'
    )
    process.exitCode = 1
    return
  }

  console.log(`Fetching OpenAPI doc from ${url}`)
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`Failed to fetch OpenAPI doc: HTTP ${response.status} ${response.statusText}`)
  }
  let raw = await response.text()

  // Fail fast if the response isn't valid JSON before we start string-patching it.
  JSON.parse(raw)

  for (const correction of KNOWN_CORRECTIONS) {
    if (raw.includes(correction.find)) {
      raw = raw.replace(correction.find, correction.replace)
      console.log(`Applied correction: ${correction.name}`)
    } else if (raw.includes(correction.replace)) {
      console.log(
        `Correction "${correction.name}" is a no-op — the source already matches the ` +
        'corrected value. Consider removing it from KNOWN_CORRECTIONS in ' +
        'fetch-and-patch-docs.mjs.'
      )
    } else {
      throw new Error(
        `Correction "${correction.name}" did not match the fetched doc (neither the old nor ` +
        'the corrected shape was found). The upstream schema likely changed — update or ' +
        'remove this correction in fetch-and-patch-docs.mjs before continuing.\n' +
        `Reason this correction exists: ${correction.reason}`
      )
    }
  }

  writeFileSync(OUTPUT_PATH, raw)
  console.log(`Wrote ${OUTPUT_PATH}`)
}

main().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
